// qa/ensure-qa-config.js
const fs = require('fs');
const path = require('path');

const qaCfgPath = path.join(__dirname, 'next.config.compiled.js');

// Safe shim content: no reference to "next.config.original"
const SAFE_SHIM = `// AUTO-GENERATED by ensure-qa-config.js
// Robust shim for Playwright's webServer. Do NOT depend on adapter temp files.
function tryLoad(mod){try{const c=require(mod);return c&&c.default?c.default:c;}catch{return null;}}
const cfg = tryLoad("../next.config.ts") || tryLoad("../next.config.mjs") || tryLoad("../next.config.js") || {};
module.exports = cfg;
`;

// Write/overwrite the QA shim every time before tests
fs.writeFileSync(qaCfgPath, SAFE_SHIM, 'utf8');

// Belt-and-suspenders: fail if the bad string is still present anywhere in qa/
const qaDir = __dirname;
function containsBadString(p) {
  const s = fs.readFileSync(p, 'utf8');
  return s.includes('next.config.original');
}
function scan(dir) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const stat = fs.statSync(full);
    if (stat.isDirectory()) scan(full);
    else if (stat.isFile()) {
      if (containsBadString(full)) {
        console.error('[QA GUARD] Found forbidden "next.config.original" in:', full);
        process.exit(1);
      }
    }
  }
}
scan(qaDir);

// Scrub env that might force Next to pick a custom config
delete process.env.NEXT_CONFIG_FILE;
console.log('[QA] next.config.compiled.js rewritten and env scrubbed OK');
