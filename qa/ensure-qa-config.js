// qa/ensure-qa-config.js
const fs = require('fs');
const path = require('path');

const qaCfgPath = path.join(__dirname, 'next.config.compiled.js');
const rootJsStub = path.join(process.cwd(), 'next.config.original.js');
const rootTsStub = path.join(process.cwd(), 'next.config.original.ts');

// Safe shim for QA (no references to adapter temp files)
const SAFE_SHIM = `// AUTO-GENERATED by ensure-qa-config.js
function tryLoad(mod){try{const c=require(mod);return c&&c.default?c.default:c;}catch{return null;}}
const cfg = tryLoad("../next.config.ts") || tryLoad("../next.config.mjs") || tryLoad("../next.config.js") || {};
module.exports = cfg;
`;

fs.writeFileSync(qaCfgPath, SAFE_SHIM, 'utf8');

// Ensure a root stub exists for adapter wrapper require('./next.config.original')
if (!fs.existsSync(rootJsStub) && !fs.existsSync(rootTsStub)) {
  fs.writeFileSync(
    rootJsStub,
    `/** Auto-created stub for CI postbuild */\nmodule.exports = {};\n`,
    'utf8'
  );
}

// Scrub env that might force a custom config path
delete process.env.NEXT_CONFIG_FILE;

console.log('[QA] next.config.compiled.js + next.config.original stub ready; env scrubbed.');
